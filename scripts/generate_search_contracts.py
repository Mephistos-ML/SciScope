#!/usr/bin/env python3
"""Generate the frontend version contract from its declared Python owner.

Read declared ranking DTOs with AST instead of importing application composition
and deployment configuration. Unsupported annotations fail instead of guessing.
"""

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(root: Path) -> str:
    tree = ast.parse(
        (root / "backend/app/services/search/ranking/models.py").read_text()
    )
    wanted = {
        "RANKING_POLICY_VERSION",
        "LEGACY_RANKING_POLICY_VERSIONS",
        "RANKING_BREAKDOWN_SCHEMA_VERSION",
        "LEGACY_LOG_MATCH_BREAKDOWN_SCHEMA_VERSIONS",
    }
    values = {}
    for node in tree.body:
        names = (
            [node.target]
            if isinstance(node, ast.AnnAssign)
            else node.targets
            if isinstance(node, ast.Assign)
            else []
        )
        for name in names:
            if isinstance(name, ast.Name) and name.id in wanted:
                values[name.id] = ast.literal_eval(node.value)
    if set(values) != wanted:
        raise ValueError("Missing literal ranking version declarations")
    current = values["RANKING_POLICY_VERSION"]
    schema = values["RANKING_BREAKDOWN_SCHEMA_VERSION"]
    policies = [*values["LEGACY_RANKING_POLICY_VERSIONS"], current]
    schemas = [*values["LEGACY_LOG_MATCH_BREAKDOWN_SCHEMA_VERSIONS"], schema]
    if len(set(policies)) != len(policies) or len(set(schemas)) != len(schemas):
        raise ValueError("Current and retained contract versions must be distinct")
    contracts = (
        "// Generated by scripts/generate_search_contracts.py. Do not edit.\n\n"
        f"export const CURRENT_RANKING_POLICY_VERSION = {json.dumps(current)} as const;\n"
        f"export const CURRENT_RANKING_BREAKDOWN_SCHEMA_VERSION = {schema} as const;\n"
        f"export const SUPPORTED_RANKING_POLICY_VERSIONS = {json.dumps(policies)} as const;\n"
        f"export const SUPPORTED_LOG_MATCH_BREAKDOWN_SCHEMA_VERSIONS = {json.dumps(schemas)} as const;\n"
        "export type RankingPolicyVersion = typeof SUPPORTED_RANKING_POLICY_VERSIONS[number];\n"
    )
    retrieval = ast.parse(
        (root / "backend/app/services/search/retrieval/models.py").read_text()
    )
    location = next(
        node.value
        for node in retrieval.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(t, ast.Name) and t.id == "RetrievalMatchLocation"
            for t in node.targets
        )
    )
    names = {
        "LocationMatchCount",
        "RankingFeatures",
        "LocationScoreContribution",
        "PopularityScoreContribution",
        "RankingScoreBreakdown",
    }

    def ts_type(node: ast.expr) -> str:
        if isinstance(node, ast.Name):
            if node.id in {"int", "float"}:
                return "number"
            if node.id == "str":
                return "string"
            if node.id in names or node.id == "RetrievalMatchLocation":
                return node.id
        if isinstance(node, ast.Constant) and node.value is None:
            return "null"
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
            return f"{ts_type(node.left)} | {ts_type(node.right)}"
        if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
            if node.value.id == "Literal":
                items = (
                    node.slice.elts
                    if isinstance(node.slice, ast.Tuple)
                    else [node.slice]
                )
                return " | ".join(json.dumps(ast.literal_eval(item)) for item in items)
            if node.value.id == "tuple" and isinstance(node.slice, ast.Tuple):
                if (
                    len(node.slice.elts) == 2
                    and isinstance(node.slice.elts[1], ast.Constant)
                    and node.slice.elts[1].value is Ellipsis
                ):
                    return f"readonly {ts_type(node.slice.elts[0])}[]"
        raise ValueError(
            f"Unsupported ranking contract annotation: {ast.unparse(node)}"
        )

    if not isinstance(location, ast.Subscript) or not isinstance(
        location.slice, ast.Tuple
    ):
        raise ValueError("RetrievalMatchLocation must declare a literal vocabulary")
    location_values = [ast.literal_eval(item) for item in location.slice.elts]
    contracts += f"\nexport const RETRIEVAL_MATCH_LOCATIONS = {json.dumps(location_values)} as const;\n"
    contracts += "export type RetrievalMatchLocation = typeof RETRIEVAL_MATCH_LOCATIONS[number];\n"
    found = set()
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name in names:
            found.add(node.name)
            fields = [
                f"  {field.target.id}: {ts_type(field.annotation)};"
                for field in node.body
                if isinstance(field, ast.AnnAssign)
                and isinstance(field.target, ast.Name)
            ]
            contracts += (
                f"\nexport type {node.name} = {{\n" + "\n".join(fields) + "\n};\n"
            )
    if found != names:
        raise ValueError("Missing declared ranking DTOs")
    return contracts


def generate(root: Path, *, check: bool) -> None:
    target = root / "frontend/src/types/searchContracts.generated.ts"
    content = render(root)
    if check:
        if not target.exists() or target.read_text() != content:
            raise ValueError(
                "Generated search contracts are stale; run python scripts/generate_search_contracts.py"
            )
    else:
        target.write_text(content)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generate(ROOT, check=args.check)
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc
